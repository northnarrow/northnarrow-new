fn render_layer(inp: &Inputs) -> String {
    let p = &inp.pinned;
    let map = by_technique(inp);
    let max = map.values().map(Vec::len).max().unwrap_or(1).max(1);
    let techniques: Vec<Value> = Tactic::ALL
        .iter()
        .flat_map(|t| map.iter().filter(move |((_, tt), _)| tt == t))
        .map(|((tech, tactic), rules)| {
            let metadata: Vec<Value> = rules
                .iter()
                .map(
                    |id| json!({"name": "rule", "value": format!("{id} ({})", status_of(inp, id))}),
                )
                .collect();
            json!({
                "techniqueID": tech,
                "tactic": tactic.shortname(),
                "score": rules.len(),
                "comment": rules.join(", "),
                "enabled": true,
                "metadata": metadata,
                "showSubtechniques": false,
            })
        })
        .collect();
    let layer = json!({
        "name": "NorthNarrow rules",
        "versions": {
            "attack": p.version.split('.').next().unwrap_or(""),
            "navigator": NAVIGATOR_VERSION,
            "layer": LAYER_FORMAT,
        },
        "domain": crate::decision::attack::ATTACK_DOMAIN,
        "description": format!(
            "The techniques NorthNarrow's rules map to (score: the number of rules). Generated \
             by `cargo xtask attack-coverage`; see docs/detection/ATTACK_COVERAGE.md. ATT&CK \
             content: {}",
            p.designation
        ),
        "filters": {"platforms": ["Linux"]},
        "sorting": 3,
        "layout": {
            "layout": "side",
            "showID": true,
            "showName": true,
            "showAggregateScores": false,
            "countUnscored": false,
            "aggregateFunction": "average",
            "expandedSubtechniques": "annotated",
        },
        "hideDisabled": false,
        "techniques": techniques,
        "gradient": {"colors": ["#ffffff", "#66b1ff"], "minValue": 0, "maxValue": max},
        "legendItems": [],
        "metadata": [
            {"name": "ATT&CK", "value": format!("Enterprise {}", p.version)},
            {"name": "source", "value": format!("{} {} ({})", p.source, p.file, p.commit)},
        ],
        "links": [],
        "showTacticRowBackground": false,
        "tacticRowBackground": "#dddddd",
        "selectTechniquesAcrossTactics": true,
        "selectSubtechniquesWithParent": false,
        "selectVisibleTechniques": false,
    });
    let mut s = serde_json::to_string_pretty(&layer).expect("a JSON value serialises");
    s.push('\n');
    s
}

/// The three documents for the repository at `root`: `(path, contents)`.
pub fn render(root: &Path) -> Result<Vec<(&'static str, String)>, String> {
    let inp = inputs(root)?;
    Ok(vec![
        (COVERAGE_MD, render_coverage(&inp)),
        (CATALOGUE_MD, render_catalogue(&inp)),
        (LAYER_JSON, render_layer(&inp)),
    ])
}
