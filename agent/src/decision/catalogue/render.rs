/// One row of the pinned id list.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct PinnedRow {
    pub kind: String,
    pub status: String,
    pub name: String,
    /// Tactic short names (a technique's), or the tactic's own.
    pub tactics: Vec<String>,
    pub replaced_by: Option<String>,
}

/// The pinned id list: its provenance header and its rows by id.
#[derive(Debug, Clone)]
pub struct Pinned {
    /// The copyright designation the Terms of Use require, verbatim.
    pub designation: String,
    pub source: String,
    pub file: String,
    pub commit: String,
    pub sha256: String,
    /// `20.0`, the `version:` line's first word.
    pub version: String,
    pub rows: BTreeMap<String, PinnedRow>,
}

impl Pinned {
    /// `T1053.003` → `Scheduled Task/Job: Cron` (ATT&CK's way of naming a
    /// sub-technique); a tactic or a data component by its name.
    pub fn display_name(&self, id: &str) -> String {
        let name = self.rows.get(id).map(|r| r.name.as_str()).unwrap_or("?");
        match id.split_once('.') {
            Some((parent, _)) if id.starts_with('T') => {
                let p = self
                    .rows
                    .get(parent)
                    .map(|r| r.name.as_str())
                    .unwrap_or("?");
                format!("{p}: {name}")
            }
            _ => name.to_string(),
        }
    }

    /// The id a V2 row's technique is in this version: itself, or what it
    /// was revoked by (followed to the end).
    pub fn current(&self, id: &str) -> String {
        let mut id = id.to_string();
        for _ in 0..8 {
            match self.rows.get(&id).and_then(|r| r.replaced_by.clone()) {
                Some(next) => id = next,
                None => break,
            }
        }
        id
    }
}

/// Parse the pinned id list.
pub fn parse_pinned(text: &str) -> Result<Pinned, String> {
    let mut header: BTreeMap<&str, String> = BTreeMap::new();
    let mut designation = None;
    let mut rows = BTreeMap::new();
    let mut seen_columns = false;
    for (n, line) in text.lines().enumerate() {
        if let Some(c) = line.strip_prefix('#') {
            let c = c.trim();
            if let Some(d) = c.strip_prefix("\"©").and_then(|d| d.strip_suffix('"')) {
                designation = Some(format!("©{d}"));
            }
            for key in ["source", "file", "commit", "sha256", "version"] {
                if let Some(v) = c.strip_prefix(&format!("{key}:")) {
                    header.insert(key, v.trim().to_string());
                }
            }
            continue;
        }
        if line.trim().is_empty() {
            continue;
        }
        let cells: Vec<&str> = line.split('\t').collect();
        if cells.len() != 6 {
            return Err(format!(
                "{ATTACK_IDS_FILE}:{}: {} cells, not 6",
                n + 1,
                cells.len()
            ));
        }
        if !seen_columns {
            if cells != ["id", "kind", "status", "name", "tactics", "replaced_by"] {
                return Err(format!(
                    "{ATTACK_IDS_FILE}:{}: not the column header",
                    n + 1
                ));
            }
            seen_columns = true;
            continue;
        }
        let row = PinnedRow {
            kind: cells[1].to_string(),
            status: cells[2].to_string(),
            name: cells[3].to_string(),
            tactics: match cells[4] {
                "-" => Vec::new(),
                t => t.split(',').map(str::to_string).collect(),
            },
            replaced_by: (cells[5] != "-").then(|| cells[5].to_string()),
        };
        if rows.insert(cells[0].to_string(), row).is_some() {
            return Err(format!("{ATTACK_IDS_FILE}: {} listed twice", cells[0]));
        }
    }
    let get = |k: &str| {
        header
            .get(k)
            .cloned()
            .ok_or_else(|| format!("{ATTACK_IDS_FILE}: no `# {k}:` line"))
    };
    Ok(Pinned {
        designation: designation
            .ok_or_else(|| format!("{ATTACK_IDS_FILE}: no quoted \"© …\" designation"))?,
        source: get("source")?,
        file: get("file")?,
        commit: get("commit")?,
        sha256: get("sha256")?,
        version: get("version")?
            .split_whitespace()
            .next()
            .unwrap_or("")
            .to_string(),
        rows,
    })
}

/// A registry file of `docs/validation/`: rows keyed by the header's
/// column names (`#` lines are comments).
pub fn parse_tsv(text: &str) -> Vec<BTreeMap<String, String>> {
    let mut header: Option<Vec<String>> = None;
    let mut rows = Vec::new();
    for line in text.lines() {
        if line.starts_with('#') || line.trim().is_empty() {
            continue;
        }
        let cells: Vec<String> = line.split('\t').map(|c| c.trim().to_string()).collect();
        match &header {
            None => header = Some(cells),
            Some(h) => rows.push(h.iter().cloned().zip(cells).collect()),
        }
    }
    rows
}

/// The data rows of the first table under the `## ` heading of `text`
/// that starts with `heading`.
pub fn md_table(text: &str, heading: &str) -> Vec<Vec<String>> {
    let mut in_section = false;
    let mut seen_header = false;
    let mut rows = Vec::new();
    for line in text.lines() {
        if let Some(title) = line.strip_prefix("## ") {
            if in_section {
                break;
            }
            in_section = title.starts_with(heading);
            continue;
        }
        let line = line.trim();
        if !in_section || !line.starts_with('|') {
            if seen_header && !rows.is_empty() {
                break;
            }
            continue;
        }
        let cells: Vec<String> = line
            .trim_matches('|')
            .split('|')
            .map(|c| c.trim().to_string())
            .collect();
        if !seen_header {
            seen_header = true;
            continue;
        }
        if cells
            .iter()
            .all(|c| c.chars().all(|ch| ch == '-' || ch == ':'))
        {
            continue;
        }
        rows.push(cells);
    }
    rows
}

/// A rule the agent can record, as the documents need it.
pub struct ShippedRule {
    pub id: &'static str,
    pub name: &'static str,
    pub category: &'static str,
    pub attack: &'static [AttackRef],
}

/// Every rule the agent can record, once each, in evaluation order: the
/// production engine's rules (built as main.rs builds them, over empty
/// operator state) and NN-L-AT-001 and NN-L-EPG-001/002 (lab PR 219), which
/// `process_event` issues outside the engine (the denominator of
/// `docs/validation/v2-rules.tsv`), then NN-L-EXECQ-001 (lab PR 223) and
/// NN-L-EXECPOL-001 / NN-L-EXECENV-001..003 (lab PR 226), which the exec
/// quarantine's and the exec policy's controllers record (not in that
/// denominator).
pub fn shipped_rules() -> Vec<ShippedRule> {
    use crate::config::comm_allowlist::CommAllowlist;
    use crate::net::blocklist::{Ja3Blocklist, NetBlocklist};
    let engine = rules::default_rules_with_net(
        Arc::new(NetBlocklist::default()),
        Arc::new(Ja3Blocklist::default()),
        Arc::new(Mutex::new(rules::net::DnsBurstWindow::default())),
        Arc::new(CommAllowlist::default()),
        Arc::new(CommAllowlist::default()),
        Arc::new(Mutex::new(rules::net::BeaconWindow::default())),
        Arc::new(crate::net::dns_cache::DnsCache::default()),
        crate::anti_tamper::trusted_installer::TrustedInstallerOverride::inert_arc(),
        crate::posture::lineage::AuthSessionTracker::default(),
        crate::canary::readers::CanaryReaders::default(),
        Arc::new(Mutex::new(
            crate::decision::correlation::CorrelationStore::new(),
        )),
        // Lab PR 224: no configured resolver, the default fan-out thresholds.
        rules::net::NetRuleConfig::default(),
        // Lab PR 225: the ransomware tracker and the built-in security tools.
        Arc::new(crate::impact::RansomTracker::new(
            crate::posture::lineage::AuthSessionTracker::default(),
        )),
        Arc::new(crate::impair::DefenseDetector::new(
            Arc::new(crate::impair::SecurityTools::builtin()),
            crate::posture::lineage::AuthSessionTracker::default(),
            None,
        )),
    );
    let direct: [Box<dyn Rule>; 3] = [
        Box::new(rules::anti_tamper::NnLAt001AntiTamperDenial),
        Box::new(rules::epg::NnLEpg001CredentialPostcondition),
        Box::new(rules::epg::NnLEpg002NamespaceRootPostcondition),
    ];
    let mut seen = BTreeSet::new();
    let mut rules: Vec<ShippedRule> = engine
        .iter()
        .chain(direct.iter())
        .filter(|r| seen.insert(r.id()))
        .map(|r| ShippedRule {
            id: r.id(),
            name: r.name(),
            category: r.category(),
            attack: r.attack(),
        })
        .collect();
    // Lab PR 223: the exec quarantine's records are the controller's, not a
    // `Rule`'s; their references are `execq::ATTACK`.
    rules.push(ShippedRule {
        id: crate::execq::RULE_ID,
        name: crate::execq::RULE_NAME,
        category: crate::execq::CATEGORY,
        attack: crate::execq::ATTACK,
    });
    // Lab PR 226: the exec policy's four rules, recorded by its controller
    // too.
    {
        use crate::execpol::{self as ep, record as epr};
        for (id, name, attack) in [
            (ep::RULE_EXEC, ep::RULE_EXEC_NAME, epr::ATTACK_EXEC),
            (ep::RULE_PRELOAD, ep::RULE_PRELOAD_NAME, epr::ATTACK_PRELOAD),
            (ep::RULE_ENV, ep::RULE_ENV_NAME, epr::ATTACK_ENV),
            (ep::RULE_MAP, ep::RULE_MAP_NAME, epr::ATTACK_MAP),
        ] {
            rules.push(ShippedRule {
                id,
                name,
                category: ep::CATEGORY,
                attack,
            });
        }
    }
    rules
}

/// What the documents say about a rule's validation.
#[derive(Debug, Clone)]
struct Validation {
    /// `critical` (in the V2 Critical sub-gate) or `-`.
    gate: String,
    /// matrix.md's status for a sub-gate rule; for another, the kinds of
    /// test the catalogue cites (`unit`, `e2e`, `lab`), joined with `+`.
    status: String,
}

fn cited_kinds(doc: &RuleDoc) -> String {
    let mut kinds = Vec::new();
    for (prefix, kind) in [
        ("agent/src/", "unit"),
        ("agent/tests/", "e2e"),
        ("deploy/lab/", "lab"),
    ] {
        if doc
            .tests
            .iter()
            .any(|t| t.starts_with(prefix) || unit_of_a_crate(t, kind))
        {
            kinds.push(kind);
        }
    }
    if kinds.is_empty() {
        "no proof".to_string()
    } else {
        kinds.join("+")
    }
}

/// R08b (lab PR 251): a unit test of a crate of `crates/` (the engine's
/// rules moved to nn-core with their tests) is a unit test as one of
/// `agent/src/` is.
fn unit_of_a_crate(test: &str, kind: &str) -> bool {
    kind == "unit"
        && test.strip_prefix("crates/").is_some_and(|t| {
            t.split_once('/')
                .is_some_and(|(_, r)| r.starts_with("src/"))
        })
}

/// Everything the renderers read.
struct Inputs {
    pinned: Pinned,
    rules: Vec<ShippedRule>,
    validation: BTreeMap<String, Validation>,
    /// v2-techniques.tsv rows.
    v2_rows: Vec<BTreeMap<String, String>>,
    /// The V2 sweep still says HALT.
    halted: bool,
}

fn read(root: &Path, rel: &str) -> Result<String, String> {
    std::fs::read_to_string(root.join(rel)).map_err(|e| format!("read {rel}: {e}"))
}

fn inputs(root: &Path) -> Result<Inputs, String> {
    let pinned = parse_pinned(&read(root, ATTACK_IDS_FILE)?)?;
    let rules = shipped_rules();
    let mut subgate = BTreeMap::new();
    for row in md_table(&read(root, MATRIX_MD)?, "Critical sub-gate") {
        if row.len() >= 7 {
            subgate.insert(row[0].trim_matches('`').to_string(), row[6].clone());
        }
    }
    let mut validation = BTreeMap::new();
    for r in parse_tsv(&read(root, RULES_TSV)?) {
        let id = r.get("rule_id").cloned().unwrap_or_default();
        let gate = r.get("gate").cloned().unwrap_or_else(|| "-".into());
        let status = match subgate.get(&id) {
            Some(s) => s.clone(),
            None => super::doc(&id)
                .map(cited_kinds)
                .unwrap_or_else(|| "no proof".into()),
        };
        validation.insert(id, Validation { gate, status });
    }
    Ok(Inputs {
        pinned,
        rules,
        validation,
        v2_rows: parse_tsv(&read(root, TECHNIQUES_TSV)?),
        halted: read(root, SWEEP_MD)?.contains("**HALT.**"),
    })
}

