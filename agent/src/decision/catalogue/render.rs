/// A Markdown table cell: no `|`, no line break.
/// Markdown prose: `<` and `>` outside code spans escaped, so a
/// `/proc/<pid>/mem` is not read as an HTML tag.
fn md_text(s: &str) -> String {
    let mut out = String::with_capacity(s.len());
    let mut in_code = false;
    for c in s.chars() {
        match c {
            '`' => {
                in_code = !in_code;
                out.push(c);
            }
            '<' if !in_code => out.push_str("&lt;"),
            '>' if !in_code => out.push_str("&gt;"),
            _ => out.push(c),
        }
    }
    out
}

fn cell(s: &str) -> String {
    s.replace('|', "\\|").replace('\n', " ")
}

/// GitHub's anchor for a heading.
fn slug(heading: &str) -> String {
    heading
        .trim()
        .to_lowercase()
        .chars()
        .filter_map(|c| match c {
            ' ' => Some('-'),
            '-' | '_' => Some(c),
            c if c.is_alphanumeric() => Some(c),
            _ => None,
        })
        .collect()
}

fn sensor_name(s: Sensor) -> &'static str {
    match s {
        Sensor::Exec => "exec (sched_process_exec, bprm_check_security)",
        Sensor::File => "file (file_open LSM, FIM drift)",
        Sensor::ModuleLoad => "kernel module load (kernel_read_file, kernel_load_data)",
        Sensor::Network => "network (TCP connect, DNS, flows, listeners)",
        Sensor::AntiTamper => "anti-tamper (LSM denials, bpf() syscalls)",
        Sensor::Canary => "canary trip",
        Sensor::IoUring => "io_uring (ring setup and use)",
        // Lab PR 219.
        Sensor::ExploitGuard => {
            "exploit guard (commit_creds, namespace and root switches; capable, exec and \
             file_open in lite, raw_syscalls in strict)"
        }
    }
}

fn join_debug<T: std::fmt::Debug>(items: &[T]) -> String {
    items
        .iter()
        .map(|i| format!("{i:?}"))
        .collect::<Vec<_>>()
        .join(", ")
}

fn attack_line(p: &Pinned, refs: &[AttackRef]) -> String {
    refs.iter()
        .map(|r| {
            format!(
                "{} {} ({})",
                r.technique,
                p.display_name(r.technique.as_str()),
                r.tactic.name()
            )
        })
        .collect::<Vec<_>>()
        .join("; ")
}

/// The sensors and data components of `docs`, each once, in order.
fn data_line<'a>(p: &Pinned, docs: impl IntoIterator<Item = &'a RuleDoc>) -> String {
    let mut sensors: Vec<Sensor> = Vec::new();
    let mut dcs: Vec<&str> = Vec::new();
    for d in docs {
        for s in d.sensors {
            if !sensors.contains(s) {
                sensors.push(*s);
            }
        }
        for dc in d.data_components {
            if !dcs.contains(dc) {
                dcs.push(dc);
            }
        }
    }
    let sensors: Vec<&str> = sensors.into_iter().map(sensor_name).collect();
    let dcs: Vec<String> = dcs
        .into_iter()
        .map(|d| format!("{d} {}", p.display_name(d)))
        .collect();
    format!("{} — {}", sensors.join("; "), dcs.join(", "))
}

fn designation_block(p: &Pinned) -> String {
    format!(
        "MITRE ATT&CK® Enterprise {v}: the ids, tactics and names are MITRE's, from the pinned list \
         [`attack-enterprise-{v}.tsv`](attack-enterprise-{v}.tsv) (bundle `{file}` of {src} at \
         commit `{commit}`, sha256 `{sha}`), under the ATT&CK Terms of Use \
         ([`LICENSES/MITRE_ATTACK_ToU-{v}.md`](../../LICENSES/MITRE_ATTACK_ToU-{v}.md), \
         `NOTICES.md`).\n\n> {d}\n",
        v = p.version,
        file = p.file,
        src = p.source,
        commit = p.commit,
        sha = p.sha256,
        d = p.designation,
    )
}

/// `(technique, tactic)` → the rules mapping it, in evaluation order.
fn by_technique(inp: &Inputs) -> BTreeMap<(&'static str, Tactic), Vec<&'static str>> {
    let mut m: BTreeMap<(&'static str, Tactic), Vec<&'static str>> = BTreeMap::new();
    for r in &inp.rules {
        for a in r.attack {
            let v = m.entry((a.technique.as_str(), a.tactic)).or_default();
            if !v.contains(&r.id) {
                v.push(r.id);
            }
        }
    }
    m
}

fn status_of(inp: &Inputs, id: &str) -> String {
    inp.validation
        .get(id)
        .map(|v| v.status.clone())
        .unwrap_or_else(|| "no proof".into())
}

/// The V2 rows whose technique is `technique` in this version.
fn v2_rows_for(inp: &Inputs, technique: &str) -> Vec<String> {
    inp.v2_rows
        .iter()
        .filter(|r| inp.pinned.current(&r["technique"]) == technique)
        .map(|r| r["id"].clone())
        .collect()
}

