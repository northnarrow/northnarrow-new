fn render_coverage(inp: &Inputs) -> String {
    let p = &inp.pinned;
    let map = by_technique(inp);
    let techniques: BTreeSet<&str> = map.keys().map(|(t, _)| *t).collect();
    let subs = techniques.iter().filter(|t| t.contains('.')).count();
    let tactics: BTreeSet<Tactic> = map.keys().map(|(_, t)| *t).collect();
    let mapped = inp.rules.iter().filter(|r| !r.attack.is_empty()).count();
    let mut o = String::new();
    let _ = writeln!(o, "# ATT&CK coverage\n\n{GENERATED}\n");
    o.push_str(&designation_block(p));
    let _ = writeln!(
        o,
        "\n{mapped} of the {n} rules the agent can record map to {t} techniques and \
         sub-techniques ({subs} of them sub-techniques) under {k} of the {all} Enterprise \
         tactics. Each rule declares its references in code (`Rule::attack`); a detection \
         record carries their ids in `mitre`, with `mitre_version` `{ATTACK_VERSION}`. The rule \
         catalogue ([`RULE_CATALOGUE.md`](RULE_CATALOGUE.md)) says what each rule observes; \
         the ATT&CK Navigator layer \
         ([`attack-navigator-layer.json`](attack-navigator-layer.json)) draws this table.\n",
        n = inp.rules.len(),
        t = techniques.len(),
        k = tactics.len(),
        all = Tactic::ALL.len(),
    );
    o.push_str(
        "A technique listed here has at least one rule whose detection is evidence of it: it \
         is not a claim that every procedure of the technique is detected, and MITRE's \
         disclaimer applies (ATT&CK does not enumerate every way to perform a technique).\n\n",
    );
    let _ = writeln!(
        o,
        "Validation: a rule in the V2 Critical sub-gate carries the status \
         [`matrix.md`](../validation/matrix.md) gives it (`campaign`, `e2e`, `e2e-event`, \
         `e2e-flaky`, `unit`, `no proof`); for any other rule it is the kinds of test the \
         catalogue cites (`unit`, `e2e`, `lab`: a lab script that exercises the rule, not a \
         recorded lab run), not reviewed row by row. {}\n",
        if inp.halted {
            "The V2 campaign has not run (its sweep document says HALT): no row has campaign \
             evidence."
        } else {
            "See matrix.md for the campaign's rows."
        }
    );
    o.push_str("## By tactic\n\n| Tactic | Techniques | Rules |\n|---|---|---|\n");
    for t in Tactic::ALL {
        let techs: BTreeSet<&str> = map
            .keys()
            .filter(|(_, tt)| *tt == t)
            .map(|(x, _)| *x)
            .collect();
        if techs.is_empty() {
            let _ = writeln!(o, "| {} ({}) | - | - |", t.name(), t.id());
            continue;
        }
        let rules: BTreeSet<&str> = map
            .iter()
            .filter(|((_, tt), _)| *tt == t)
            .flat_map(|(_, r)| r.iter().copied())
            .collect();
        let _ = writeln!(
            o,
            "| {} ({}) | {} | {} |",
            t.name(),
            t.id(),
            techs.len(),
            rules.len()
        );
    }
    o.push_str(
        "\n## Techniques\n\nOne row per technique and tactic. Rules are listed with their \
         validation status; *Sensor* is the agent's sensor and the ATT&CK data components its \
         events are; *V2 rows* are the pre-registered rows of \
         [`v2-techniques.tsv`](../validation/v2-techniques.tsv) for the technique (by its id \
         in this version).\n\n\
         | Technique | Tactic | Rules (validation) | Sensor — data components | V2 rows |\n\
         |---|---|---|---|---|\n",
    );
    for t in Tactic::ALL {
        for ((tech, tt), rule_ids) in map.iter().filter(|((_, tt), _)| *tt == t) {
            let sensors = data_line(p, rule_ids.iter().filter_map(|id| super::doc(id)));
            let rules: Vec<String> = rule_ids
                .iter()
                .map(|id| {
                    format!(
                        "[`{id}`](RULE_CATALOGUE.md#{}) ({})",
                        slug(id),
                        status_of(inp, id)
                    )
                })
                .collect();
            let rows = v2_rows_for(inp, tech);
            let _ = writeln!(
                o,
                "| {tech} {} | {} ({}) | {} | {} | {} |",
                cell(&p.display_name(tech)),
                tt.name(),
                tt.id(),
                rules.join("<br>"),
                cell(&sensors),
                if rows.is_empty() {
                    "-".into()
                } else {
                    rows.join(", ")
                }
            );
        }
    }
    o.push_str(
        "\n## V2 rows without a rule\n\nThe pre-registered technique rows the campaign runs \
         and reports as an anti-tamper denial, a signed integrity drift or a known gap, \
         rather than as a rule's detection; a revoked id is given with its id in this \
         version.\n\n| Row | Technique | Expected | Note |\n|---|---|---|---|\n",
    );
    for r in inp.v2_rows.iter().filter(|r| r["expected"] != "rule") {
        let id = &r["technique"];
        let now = p.current(id);
        let tech = if &now == id {
            format!("{id} {}", p.display_name(id))
        } else {
            format!("{id} (revoked; now {now} {})", p.display_name(&now))
        };
        let _ = writeln!(
            o,
            "| {} | {} | {} | {} |",
            r["id"],
            cell(&tech),
            r["expected"],
            cell(&md_text(&r["note"]))
        );
    }
    let revoked: Vec<&BTreeMap<String, String>> = inp
        .v2_rows
        .iter()
        .filter(|r| p.current(&r["technique"]) != r["technique"])
        .collect();
    if !revoked.is_empty() {
        let _ = writeln!(
            o,
            "\n## V2 rows on ids revoked in {v}\n\n`v2-techniques.tsv` is frozen (its sha256 \
             is in matrix.md) and keeps the ids it was registered with; they read as \
             follows in {v}.\n\n| Row | Registered id | Id in {v} |\n|---|---|---|",
            v = p.version
        );
        for r in revoked {
            let now = p.current(&r["technique"]);
            let _ = writeln!(
                o,
                "| {} | {} {} | {now} {} |",
                r["id"],
                r["technique"],
                cell(&p.display_name(&r["technique"])),
                cell(&p.display_name(&now))
            );
        }
    }
    o
}

// ── RULE_CATALOGUE.md ───────────────────────────────────────────────

/// The id prefixes of the rules the agent issues outside the engine:
/// NN-L-AT-001 (an anti-tamper denial) and the exploit post-condition
/// guard's (lab PR 219); the exec quarantine's controller's (lab PR 223);
/// the exec policy's controller's (lab PR 226).
const OUTSIDE_ENGINE: &[&str] = &[
    "NN-L-AT-",
    "NN-L-EPG-",
    "NN-L-EXECQ-",
    "NN-L-EXECPOL-",
    "NN-L-EXECENV-",
];

fn render_catalogue(inp: &Inputs) -> String {
    let p = &inp.pinned;
    let by_id: BTreeMap<&str, &ShippedRule> = inp.rules.iter().map(|r| (r.id, r)).collect();
    let outside: Vec<&str> = inp
        .rules
        .iter()
        .map(|r| r.id)
        .filter(|id| OUTSIDE_ENGINE.iter().any(|pre| id.starts_with(pre)))
        .collect();
    let mut o = String::new();
    let _ = writeln!(o, "# Rule catalogue\n\n{GENERATED}\n");
    let _ = writeln!(
        o,
        "Every rule the agent can record ({n}): the production engine's rules and the {m} \
         the agent issues outside the engine ({list}). For each: its severities and \
         responses (the strongest first), its ATT&CK references \
         ([`ATTACK_COVERAGE.md`](ATTACK_COVERAGE.md)), the sensor and data it reads, its \
         validation status — for a rule in the V2 Critical sub-gate the status \
         [`matrix.md`](../validation/matrix.md) gives it, for any other the kinds of test its \
         entry cites ([`v2-rules.tsv`](../validation/v2-rules.tsv); `lab` names a lab script \
         that exercises the rule, not a recorded lab run) —, what it observes, its known \
         false positives and how to make it fire.\n",
        n = inp.rules.len(),
        m = outside.len(),
        list = outside.join(", ")
    );
    o.push_str(&designation_block(p));
    for (family, docs) in FAMILIES {
        let _ = writeln!(
            o,
            "\n## {family}\n\n| Rule | Name | Severity | Response | ATT&CK |\n|---|---|---|---|---|"
        );
        for d in docs {
            let Some(r) = by_id.get(d.id) else { continue };
            let techs: Vec<&str> = {
                let mut v: Vec<&str> = Vec::new();
                for a in r.attack {
                    if !v.contains(&a.technique.as_str()) {
                        v.push(a.technique.as_str());
                    }
                }
                v
            };
            let _ = writeln!(
                o,
                "| [`{}`](#{}) | {} | {} | {} | {} |",
                d.id,
                slug(d.id),
                cell(r.name),
                join_debug(d.severities),
                join_debug(d.actions),
                techs.join(", ")
            );
        }
        for d in docs {
            let Some(r) = by_id.get(d.id) else { continue };
            let v = inp.validation.get(d.id);
            let _ = writeln!(o, "\n### {}\n", d.id);
            let _ = writeln!(o, "{} — category `{}`.\n", r.name, r.category);
            o.push_str("| | |\n|---|---|\n");
            let _ = writeln!(o, "| Severity | {} |", join_debug(d.severities));
            let _ = writeln!(o, "| Response | {} |", join_debug(d.actions));
            let _ = writeln!(o, "| ATT&CK | {} |", cell(&attack_line(p, r.attack)));
            let _ = writeln!(o, "| Sensor — data | {} |", cell(&data_line(p, [d])));
            let _ = writeln!(
                o,
                "| Validation | {}{} |",
                v.map(|v| v.status.as_str()).unwrap_or("no proof"),
                if v.is_some_and(|v| v.gate == "critical") {
                    " (V2 Critical sub-gate)"
                } else {
                    ""
                }
            );
            let _ = writeln!(o, "\n**Observes.** {}\n", md_text(d.observes));
            let _ = writeln!(
                o,
                "**Known false positives.** {}\n",
                md_text(d.false_positives)
            );
            let _ = writeln!(o, "**How to test.** {}\n", md_text(d.how_to_test));
            let tests: Vec<String> = d.tests.iter().map(|t| format!("`{t}`")).collect();
            let _ = writeln!(o, "**Tests.** {}", tests.join(", "));
            if !d.attack_note.is_empty() {
                let _ = writeln!(o, "\n**ATT&CK note.** {}", md_text(d.attack_note));
            }
        }
    }
    o
}

